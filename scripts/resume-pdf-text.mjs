// Writes src/data/resume-pdf.generated.ts: the text of the PDF resume, so the engineering filter says a
// name "is not on my resume" only when the PDF does not print it either (src/data/tech-filter.ts).
// Run it after rebuilding static/nathan-rihet-resume.pdf (npm run resume-pdf):
//
//   npm run resume-text
//
// Needs pdftotext (Poppler; Git for Windows has it in mingw64). Addresses and links are left out.

import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"

const PDF = "static/nathan-rihet-resume.pdf"
const OUT = "src/data/resume-pdf.generated.ts"

const text = execFileSync("pdftotext", ["-enc", "UTF-8", PDF, "-"], { encoding: "utf8" })
const words = text
  .replace(/\S+@\S+/g, " ")
  .replace(/\b(?:https?:\/\/)?(?:[\w-]+\.)+[a-z]{2,}\/\S*/gi, " ")
  .replace(/\b(?:[\w-]+\.)+(?:com|io|org|net)\b/gi, " ")
  .replace(/\s+/g, " ")
  .trim()

writeFileSync(
  OUT,
  [
    `// Generated by scripts/resume-pdf-text.mjs from ${PDF}: do not edit, run npm run resume-text.`,
    `export const resumePdfText = ${JSON.stringify(words)}`,
    "",
  ].join("\n"),
)
console.log(`${OUT}: ${words.length} characters`)
