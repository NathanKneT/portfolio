// Builds the invisible data field of the hero automaton: the Sobel edge map
// of the Dotonbori photo, pooled down to each grid's X × Y resolution.
// Run once, by hand:  node scripts/build-automaton-field.mjs
// Output: src/components/hero-automaton/field-data.ts (a few KB, committed).

import { writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import path from "node:path"
import sharp from "sharp"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const source = path.join(root, "content/projects/night/18-_HF01673.jpg")
const target = path.join(root, "src/components/hero-automaton/field-data.ts")

// Must match GRIDS in src/components/hero-automaton/settings.ts.
// `position` is the sharp crop gravity used to fit the photo (or `region`, a
// crop of the 2000 × 1500 photo) to the grid.
// `mirror` flips the photo left to right: on desktop the hero text covers the
// left of the volume, so the busy side of the street (the buildings) has to
// be on the right, where the volume is in the clear.
// Both crops keep the buildings and leave the canal out: its reflections
// gave the bottom of the volume edges that the growth never reached.
const grids = [
  { id: "desktop", x: 40, y: 22, position: "centre", mirror: true, region: { left: 125, top: 40, width: 1750, height: 962 } },
  // Phone: a tall crop of the left side of the street, the sign tower and
  // the next building, down to the lanterns.
  { id: "phone", x: 14, y: 28, position: "centre", mirror: false, region: { left: 0, top: 60, width: 470, height: 940 } },
  { id: "fallback", x: 32, y: 18, position: "centre", mirror: true, region: { left: 125, top: 40, width: 1750, height: 984 } },
]

const SUPERSAMPLE = 6

async function edgeField({ x, y, position, mirror, region }) {
  const w = x * SUPERSAMPLE
  const h = y * SUPERSAMPLE
  const photo = region ? sharp(await sharp(source).extract(region).toBuffer()) : sharp(source)
  const grey = await photo
    .resize(w, h, { fit: "cover", position })
    .flop(mirror)
    .greyscale()
    .blur(0.8)
    .raw()
    .toBuffer()

  // Sobel gradient magnitude at the supersampled size.
  const mag = new Float32Array(w * h)
  const at = (px, py) =>
    grey[Math.min(h - 1, Math.max(0, py)) * w + Math.min(w - 1, Math.max(0, px))]
  for (let py = 0; py < h; py++) {
    for (let px = 0; px < w; px++) {
      const gx =
        at(px + 1, py - 1) + 2 * at(px + 1, py) + at(px + 1, py + 1) -
        at(px - 1, py - 1) - 2 * at(px - 1, py) - at(px - 1, py + 1)
      const gy =
        at(px - 1, py + 1) + 2 * at(px, py + 1) + at(px + 1, py + 1) -
        at(px - 1, py - 1) - 2 * at(px, py - 1) - at(px + 1, py - 1)
      mag[py * w + px] = Math.hypot(gx, gy)
    }
  }

  // Mean-pool to the grid, then normalise on the 97th percentile.
  const cells = new Float32Array(x * y)
  for (let cy = 0; cy < y; cy++) {
    for (let cx = 0; cx < x; cx++) {
      let sum = 0
      for (let sy = 0; sy < SUPERSAMPLE; sy++) {
        for (let sx = 0; sx < SUPERSAMPLE; sx++) {
          sum += mag[(cy * SUPERSAMPLE + sy) * w + cx * SUPERSAMPLE + sx]
        }
      }
      cells[cy * x + cx] = sum / (SUPERSAMPLE * SUPERSAMPLE)
    }
  }
  const sorted = Float32Array.from(cells).sort()
  const top = sorted[Math.floor(sorted.length * 0.97)] || 1

  // Row 0 of the output is the BOTTOM of the photo: grid y points up.
  const out = new Uint8Array(x * y)
  for (let cy = 0; cy < y; cy++) {
    for (let cx = 0; cx < x; cx++) {
      const v = Math.min(1, cells[(y - 1 - cy) * x + cx] / top)
      out[cy * x + cx] = Math.round(255 * Math.pow(v, 0.55))
    }
  }
  return out
}

const lines = [
  "// GENERATED by scripts/build-automaton-field.mjs. Do not edit by hand.",
  "// Sobel edge strength of the Dotonbori photo, one byte per (x, y) column,",
  "// row 0 at the bottom. The photo itself is never shipped to the hero.",
  "",
  "export const FIELD_DATA: Record<string, string> = {",
]
for (const grid of grids) {
  const field = await edgeField(grid)
  const strong = field.reduce((n, v) => n + (v >= 128 ? 1 : 0), 0)
  console.log(`${grid.id}: ${grid.x}×${grid.y}, ${field.length} bytes, ${((100 * strong) / field.length).toFixed(1)} % ≥ 128`)
  lines.push(`  ${grid.id}:`, `    "${Buffer.from(field).toString("base64")}",`)
}
lines.push("}", "")
await writeFile(target, lines.join("\n"))
console.log(`wrote ${path.relative(root, target)}`)
